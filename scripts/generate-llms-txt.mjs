#!/usr/bin/env node
/**
 * generate-llms-txt.mjs — generate the agentic-web discovery files from the
 * LIVE App Intent registry so they cannot drift from what the MCP endpoint
 * actually exposes.
 *
 * Outputs (committed, served as static assets from client/public):
 *   - client/public/.well-known/llms.txt        — agent-legible prose + the
 *     read-mostly MCP tool list, derived from listExternalSafeIntents().
 *   - client/public/.well-known/ai-plugin.json  — a ChatGPT-plugin-style
 *     manifest pointing at /api/mcp (the JSON-RPC MCP endpoint).
 *
 * The tool list is the SAME safe subset the MCP endpoint serves
 * (server/mcp/safeIntents.ts → isExternalSafeIntent), so regenerating after a
 * registry change keeps the public surface honest by construction.
 *
 * Truth-engine: describe only SHIPPED capabilities. No superlatives. Voice is
 * mechanics-first (docs/internal/marketing-os/02-voice-linter.md).
 *
 * Run:  node scripts/generate-llms-txt.mjs            (writes the files)
 *       node scripts/generate-llms-txt.mjs --check     (fails if stale)
 *
 * Importing the registry pulls in server/db.ts which requires DATABASE_URL to
 * be present; no query runs at module load, so a placeholder is enough.
 */
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const WELL_KNOWN = resolve(ROOT, "client/public/.well-known");

const CANONICAL = "https://acreos.io";

// db.ts throws without DATABASE_URL even though we never query it here.
if (!process.env.DATABASE_URL) {
  process.env.DATABASE_URL = "postgres://placeholder:placeholder@localhost:5432/placeholder";
}

const { listExternalSafeIntents } = await import(
  resolve(ROOT, "server/mcp/safeIntents.ts")
);

/** Collapse an intent description to a single tidy clause. */
function oneLine(s) {
  return (s || "").replace(/\s+/g, " ").trim().replace(/\.$/, "");
}

const safe = listExternalSafeIntents()
  .map((i) => ({ name: i.name, description: oneLine(i.description) }))
  .sort((a, b) => a.name.localeCompare(b.name));

const toolLines = safe.map((t) => `- ${t.name} — ${t.description}`).join("\n");

const llmsTxt = `# AcreOS

> AcreOS is a software platform for land investors: it manages leads, property
> inventory, deals, and seller-financed notes, and enriches parcels with public
> open data (flood zone, soil, demographics, comps). Each datum carries a
> provenance label naming its source.

This file is for AI agents. It describes the parts of AcreOS an agent can read
or call, and where to find the machine-readable contracts.

## Public, no sign-in required

- Parcel check widget: ${CANONICAL}/tools/parcel-check
  Runs a single parcel through the open-data due-diligence checks (flood, soil,
  zoning signals, basic comps) and returns a structured result. Backed by the
  public JSON endpoint GET ${CANONICAL}/api/public/parcel-check.

## Machine-readable API contract

- OpenAPI spec (JSON): ${CANONICAL}/api/docs/openapi.json
- Swagger UI: ${CANONICAL}/api/docs
  The spec is reflected from the live route set and merged with hand-curated
  schemas. Most routes require an authenticated session or an API key.

## Data provenance

- How AcreOS sources data: ${CANONICAL}/data-sources
  Names each external data source and how it is used. Requires sign-in.

## MCP endpoint (callable by other agents)

- Endpoint: POST ${CANONICAL}/api/mcp
- Transport: Model Context Protocol over JSON-RPC 2.0 (single HTTP endpoint).
- Auth: Authorization: Bearer <api-key>. The organization and the key's scopes
  are resolved from the key on every request; the org is never passed as a tool
  argument.
- Methods: initialize, ping, tools/list, tools/call.
- Scope: read-mostly. The exposed tools are the read-only, non-approval subset
  of the App Intent registry; create/update/send/generate tools and
  founder-only tools are not reachable here. Each call is rejected unless the
  key holds a scope that satisfies the tool.

### Read-mostly tools exposed over MCP (${safe.length})

${toolLines}

## Notes

- AcreOS is an operations platform, not a public bulk-data API. The parcel-check
  widget and OpenAPI spec are the open surfaces; everything else needs auth.
- Security disclosure: ${CANONICAL}/.well-known/security.txt

# Generated by scripts/generate-llms-txt.mjs from the live App Intent registry.
# Do not hand-edit — run the script so the tool list stays in sync with the
# MCP endpoint. Run \`node scripts/generate-llms-txt.mjs --check\` in CI.
`;

const aiPlugin = {
  schema_version: "v1",
  name_for_human: "AcreOS",
  name_for_model: "acreos",
  description_for_human:
    "Land-investor platform: leads, property inventory, deals, seller-financed notes, and open-data parcel enrichment.",
  description_for_model:
    "Read-mostly access to an AcreOS organization's land-investment data (leads, properties, deals, notes, dashboards) plus open-data parcel research. Org and scopes are resolved from the bearer API key on every call. Write, send, generate, and approval-gated tools are not exposed.",
  api: {
    type: "mcp",
    transport: "streamable-http",
    url: `${CANONICAL}/api/mcp`,
    protocol: "jsonrpc-2.0",
  },
  auth: {
    type: "user_http",
    authorization_type: "bearer",
    instructions:
      "Send Authorization: Bearer <api-key>. Create an API key in AcreOS Settings; the key determines the organization and the readable scopes.",
  },
  openapi_url: `${CANONICAL}/api/docs/openapi.json`,
  contact_email: "support@acreos.io",
  legal_info_url: `${CANONICAL}/terms`,
};

const aiPluginJson = JSON.stringify(aiPlugin, null, 2) + "\n";

const targets = [
  [resolve(WELL_KNOWN, "llms.txt"), llmsTxt],
  [resolve(WELL_KNOWN, "ai-plugin.json"), aiPluginJson],
];

const check = process.argv.includes("--check");

if (!existsSync(WELL_KNOWN)) mkdirSync(WELL_KNOWN, { recursive: true });

let stale = false;
for (const [path, content] of targets) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) {
    console.log(`up-to-date: ${path}`);
    continue;
  }
  if (check) {
    console.error(`STALE: ${path} — run \`node scripts/generate-llms-txt.mjs\``);
    stale = true;
  } else {
    writeFileSync(path, content);
    console.log(`wrote: ${path}`);
  }
}

if (check && stale) process.exit(1);
console.log(`\n${safe.length} read-mostly MCP tools described.`);
