#!/usr/bin/env node
/**
 * scripts/pax-capability-inventory.mjs — generate
 * docs/compliance/pax-capability-inventory.md from the rows in
 * shared/pax-capabilities.ts (PP-1).
 *
 * The rows in that file are written one per line in JSON-compatible
 * literal form, so this script needs no TS loader: it parses each row
 * line as JSON. tests/unit/paxCapabilityInventory.test.ts implements
 * the same rendering and asserts the committed doc is byte-current —
 * regenerate with: node scripts/pax-capability-inventory.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "shared/pax-capabilities.ts");
const OUT = path.join(ROOT, "docs/compliance/pax-capability-inventory.md");

const rows = {};
for (const line of fs.readFileSync(SRC, "utf8").split("\n")) {
  const m = line.match(/^ {2}"([a-z_0-9]+)": (\{.*\}),$/);
  if (m) rows[m[1]] = JSON.parse(m[2]);
}
const names = Object.keys(rows);
if (names.length === 0) {
  console.error("pax-capability-inventory: no rows parsed from shared/pax-capabilities.ts");
  process.exit(1);
}

const SWITCHES = ["executeTool", "executeSupportTool"];
const sorted = names.sort((a, b) => {
  const d = rows[a].dispatch.localeCompare(rows[b].dispatch);
  return d !== 0 ? d : a.localeCompare(b);
});
const counts = SWITCHES.map((s) => `${names.filter((n) => rows[n].dispatch === s).length} ${s}`).join(", ");
const cell = (v) => (v === undefined || v === null || v === "" ? "-" : v);
const lines = [
  "# Pax capability inventory",
  "",
  "Generated by `scripts/pax-capability-inventory.mjs` from `shared/pax-capabilities.ts` — do not edit by hand.",
  "",
  `${names.length} capabilities: ${counts}.`,
  "",
  "| Tool | Dispatch | Group | Domain | Scope | Approval | Pause-safe | Receipt | Coverage | Not covered | Family | Objects | RW row | Roles | Since |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ...sorted.map((name) => {
    const r = rows[name];
    return `| \`${name}\` | ${r.dispatch} | ${r.group} | ${cell(r.domain)} | ${cell(r.scope)} | ${r.approvalRequired} | ${r.pauseSafe} | ${r.receipt} | ${r.coverage} | ${cell(r.notCovered)} | ${r.family} | ${r.objects.join(", ")} | ${cell(r.rwRow)} | ${cell(r.roles.join(", "))} | ${r.since} |`;
  }),
  "",
];
fs.writeFileSync(OUT, lines.join("\n"));
console.log(`pax-capability-inventory: wrote ${OUT} (${names.length} rows)`);
