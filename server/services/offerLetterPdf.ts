export async function generateOfferLetterPdf(data: OfferLetterData): Promise<Buffer> {
  const doc = new jsPDF({ unit: "in", format: "letter" });
  const L = OFFER_LETTER_STRINGS[data.language === "es" ? "es" : "en"];

  const margin = 1;
  const pageWidth = 8.5;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const offerDate = data.offerDate
    ? new Date(data.offerDate).toLocaleDateString(L.locale, { year: "numeric", month: "long", day: "numeric" })
    : clock.now().toLocaleDateString(L.locale, { year: "numeric", month: "long", day: "numeric" });

  const expirationDate = clock.now();
  expirationDate.setDate(expirationDate.getDate() + (data.offerExpirationDays ?? 10));
  const expStr = expirationDate.toLocaleDateString(L.locale, { year: "numeric", month: "long", day: "numeric" });

  // ── Header ────────────────────────────────────────────────────────────────

  doc.setFontSize(22);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 58, 30); // dark forest green
  doc.text(data.buyerEntityName || data.orgName, margin, y);
  y += 0.35;

  if (data.orgAddress) {
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(80, 80, 80);
    doc.text(data.orgAddress, margin, y);
    y += 0.18;
  }
  if (data.orgPhone || data.orgEmail) {
    doc.text(
      [data.orgPhone, data.orgEmail].filter(Boolean).join("  •  "),
      margin,
      y
    );
    y += 0.18;
  }

  // Horizontal rule
  y += 0.1;
  doc.setDrawColor(180, 160, 120);
  doc.setLineWidth(0.02);
  doc.line(margin, y, pageWidth - margin, y);
  y += 0.3;

  // Date
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(60, 60, 60);
  doc.text(offerDate, margin, y);
  y += 0.35;

  // Seller address block
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text(data.sellerName, margin, y);
  y += 0.2;
  if (data.sellerAddress) {
    doc.text(data.sellerAddress, margin, y);
    y += 0.2;
  }
  y += 0.1;

  // Subject line
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 58, 30);
  doc.text(`${L.subject} — ${data.propertyAddress || `APN: ${data.apn}`}`, margin, y);
  y += 0.4;

  // Salutation
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(40, 40, 40);
  doc.text(L.dear(data.sellerName.split(" ")[0] || L.ownerFallback), margin, y);
  y += 0.3;

  // Opening paragraph
  const openingLines = doc.splitTextToSize(
    L.opening(data.buyerEntityName || data.orgName),
    contentWidth
  );
  doc.text(openingLines, margin, y);
  y += openingLines.length * 0.18 + 0.25;

  // ── Property details ───────────────────────────────────────────────────────

  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 58, 30);
  doc.text(L.propertyInfo, margin, y);
  y += 0.25;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(40, 40, 40);

  const propDetails: [string, string][] = ([
    [L.apn, data.apn],
    [L.address, data.propertyAddress || L.perCounty],
    [L.countyState, [data.county, data.state].filter(Boolean).join(", ")],
    data.acres ? [L.acreage, L.acres(data.acres.toLocaleString(L.locale))] : ["", ""],
    data.legalDescription ? [L.legal, data.legalDescription] : ["", ""],
  ] as [string, string][]).filter(([k]) => k);

  for (const [label, value] of propDetails) {
    doc.setFont("helvetica", "bold");
    doc.text(`${label}:`, margin, y);
    doc.setFont("helvetica", "normal");
    const valueX = margin + 2.5;
    const wrapped = doc.splitTextToSize(value, contentWidth - 2.5);
    doc.text(wrapped, valueX, y);
    y += Math.max(0.2, wrapped.length * 0.18);
  }

  y += 0.2;

  // ── Offer terms ────────────────────────────────────────────────────────────

  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(30, 58, 30);
  doc.text(L.offerTerms, margin, y);
  y += 0.25;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(40, 40, 40);

  const terms: [string, string][] = [
    [L.price, `$${data.purchasePrice.toLocaleString("en-US")}`],
    ...(data.earnestMoneyDeposit ? [[L.earnest, `$${data.earnestMoneyDeposit.toLocaleString("en-US")}`] as [string, string]] : []),
    [L.timeline, data.closingDateFixed
      ? L.onOrBefore(new Date(data.closingDateFixed).toLocaleDateString(L.locale, { year: "numeric", month: "long", day: "numeric" }))
      : L.daysFrom(data.closingDays ?? 30)],
  ];

  for (const [label, value] of terms) {
    doc.setFont("helvetica", "bold");
    doc.text(`${label}:`, margin, y);
    doc.setFont("helvetica", "bold");
    if (label === L.price) doc.setTextColor(30, 80, 30);
    doc.text(value, margin + 2.5, y);
    doc.setTextColor(40, 40, 40);
    y += 0.22;
  }

  // Seller financing terms if applicable
  if (data.sellerFinancing) {
    y += 0.15;
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 58, 30);
    doc.text(L.sfTitle, margin, y);
    y += 0.25;

    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(40, 40, 40);

    const sf = data.sellerFinancing;
    const sfTerms: [string, string][] = [
      [L.down, `$${sf.downPayment.toLocaleString("en-US")}`],
      [L.rate, L.perAnnum(sf.interestRate)],
      [L.term, L.termValue(sf.termMonths)],
      [L.monthly, `$${sf.monthlyPayment.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`],
    ];

    for (const [label, value] of sfTerms) {
      doc.setFont("helvetica", "bold");
      doc.text(`${label}:`, margin, y);
      doc.setFont("helvetica", "normal");
      doc.text(value, margin + 2.5, y);
      y += 0.22;
    }
  }

  y += 0.2;

  // Custom message
  if (data.customMessage) {
    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(40, 40, 40);
    const msgLines = doc.splitTextToSize(data.customMessage, contentWidth);
    doc.text(msgLines, margin, y);
    y += msgLines.length * 0.18 + 0.2;
  }

  // Expiration notice
  doc.setFontSize(10);
  doc.setFont("helvetica", "italic");
  doc.setTextColor(100, 100, 100);
  const expireText = L.expires(expStr);
  const expLines = doc.splitTextToSize(expireText, contentWidth);
  doc.text(expLines, margin, y);
  y += expLines.length * 0.16 + 0.3;

  // Closing
  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(40, 40, 40);
  doc.text(L.sincerely, margin, y);
  y += 0.4;

  doc.setFont("helvetica", "bold");
  doc.text(data.buyerEntityName || data.orgName, margin, y);
  y += 0.2;
  if (data.orgPhone) {
    doc.setFont("helvetica", "normal");
    doc.text(data.orgPhone, margin, y);
    y += 0.18;
  }
  if (data.orgEmail) {
    doc.text(data.orgEmail, margin, y);
    y += 0.18;
  }

  // Signature line
  y += 0.4;
  doc.setDrawColor(100, 100, 100);
  doc.setLineWidth(0.01);
  doc.line(margin, y, margin + 2.5, y);
  y += 0.15;
  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100, 100, 100);
  doc.text(L.signature, margin, y);

  // Footer
  const footerY = 10.5;
  doc.setFontSize(8);
  doc.setFont("helvetica", "italic");
  doc.setTextColor(150, 150, 150);
  // L1 liability shield — standing template legend above the existing
  // footer line (generated legal docs are for attorney review, not counsel
  // work-product).
  doc.setFontSize(6.5);
  doc.text(DISCLAIMER_DOCUMENT_TEMPLATE, margin, footerY - 0.45, {
    maxWidth: contentWidth,
  });
  if (L.translationNote) {
    doc.text(L.translationNote, margin, footerY - 0.62, { maxWidth: contentWidth });
  }
  doc.setFontSize(8);
  doc.text(L.notBinding(offerDate), margin, footerY, { maxWidth: contentWidth });

  // Return as Buffer
  const output = doc.output("arraybuffer");
  return Buffer.from(output);
}
