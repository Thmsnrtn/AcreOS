/**
 * L1 — liability-shield disclaimer legends for generated artifacts.
 *
 * Single source of truth for the standing "informational, not advice"
 * legends embedded into every artifact AcreOS generates (score reports,
 * worksheets, statements, document templates, AI output). Mirrors the
 * pattern of `TAX_ADVISORY_COPY` (server/utils/taxAdvisory.ts),
 * `SCREENING_ADVISORY_COPY` (compliance/ofacScreening.ts), and the
 * rmloAdvisor `DISCLAIMER` (shared/regulatory/rmloAdvisor.ts): one
 * centralized string per artifact class so the non-advice framing is
 * identical everywhere it surfaces.
 *
 * Vocabulary is drawn from docs/legal/terms-of-service.md ("AcreOS is not
 * a broker, lender, servicer, real estate agent, investment adviser, or
 * fiduciary… does not provide legal, financial, investment, or tax
 * advice") — reuse these constants rather than inventing new phrasings.
 *
 * These constants only ADD text to artifacts. They never gate, block, or
 * rewrite any generated output.
 */

