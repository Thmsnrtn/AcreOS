  "It scores the parcel, not a person: it is not a consumer credit score, is not a consumer report, " +
  "is not governed by the Fair Credit Reporting Act (FCRA), and is not lending or investment advice. " +
  "AcreOS is not a broker, lender, servicer, real estate agent, investment adviser, or fiduciary.";

